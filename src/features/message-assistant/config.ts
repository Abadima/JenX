/**
 * AnimeX link assistant configuration.
 *
 * The only place that knows what the assistant reacts to and what it answers.
 * `matcher.ts` scores these values and has no message-specific rules.
 *
 * Patterns run against one canonical clause: lowercase, apostrophes removed
 * ("i'd" is "id"), runs of 3+ identical letters collapsed, punctuation turned
 * into spaces, plurals of `pluralNouns` reduced to singular. Write patterns
 * accordingly and never use the `g` flag (stateful `lastIndex` makes matching
 * flaky).
 */

export type SectionKey = "homepage" | "catalog" | "schedule" | "community";

export interface AnimeXSection {
    label: string;
    url: string;
    /** Trigger words; they complete request frames but are not topic words. */
    keywords: readonly string[];
}

export interface AnimeXLinksConfig {
    enabled: boolean;
    /** Per-channel cooldown after a successful reply. */
    cooldownMs: number;
    /** Minimum confidence in points, out of 100. */
    threshold: number;
    /**
     * Evidence points out of 100. Topic + intent = 90: a site word inside a
     * request frame. Naming AnimeX or a section adds 10 each; penalties come
     * off the total. This is a heuristic, not a probability.
     */
    weights: {
        topic: number;
        intent: number;
        name: number;
        section: number;
    };
    /**
     * Long messages cost confidence. `maxWords` must not exceed
     * `freeWords + (100 - threshold) / penaltyPerWord`; beyond that nothing can match.
     */
    length: {
        maxWords: number;
        freeWords: number;
        penaltyPerWord: number;
    };
    pluralNouns: readonly string[];
    clauseBreakers: readonly string[];
    /** Typo repair; only tried when no request frame matches as typed. */
    typos: {
        penalty: number;
        maxFixes: number;
        targets: readonly string[];
        shorthand: Readonly<Record<string, string>>;
        /** Real words never repaired; generated by `scripts/typo-guard.ts`. */
        guard: readonly string[];
        known: readonly string[];
        segments: readonly string[];
    };
    /** Strong topic words; section words ("home", "browse") prove nothing alone. */
    keywords: readonly string[];
    topicPatterns: readonly RegExp[];
    /** Spellings of the site name; also counted as a separate evidence class. */
    names: readonly string[];
    patterns: readonly RegExp[];
    doubts: readonly { pattern: RegExp; penalty: number }[];
    clauseVetoes: readonly RegExp[];
    /** Any match discards the message before scoring. */
    negativePatterns: readonly RegExp[];
    sections: Record<SectionKey, AnimeXSection>;
    /** Static embed content; the footer is generated per match. */
    response: {
        title: string;
        description: string;
        color: number;
        thumbnail: string;
    };
}

const words = (text: string) => text.trim().split(/\s+/);

/** Accepted spellings and near-typos of the site name. */
const ANIMEX_NAMES = ["animex", "animx", "animexx", "anime x"] as const;

/** Nouns that can name a destination, alone or after the site name. */
const LINK_NOUNS = [
    "url",
    "link",
    "website",
    "site",
    "homepage",
    "page",
    "one",
] as const;

const SECTIONS: Record<SectionKey, AnimeXSection> = {
    homepage: {
        label: "Homepage",
        url: "https://animex.one",
        keywords: ["homepage", "home"],
    },
    catalog: {
        label: "Browse Catalog",
        url: "https://animex.one/catalog",
        keywords: ["catalog", "browse"],
    },
    schedule: {
        label: "Schedule",
        url: "https://animex.one/schedule",
        keywords: ["schedule", "airing"],
    },
    community: {
        label: "Community",
        url: "https://animex.one/community",
        keywords: ["community"],
    },
};

export const SECTION_KEYS = Object.keys(SECTIONS) as SectionKey[];

/** Adding a section makes its trigger words match and highlight automatically. */
const SECTION_WORDS = SECTION_KEYS.flatMap((key) => SECTIONS[key].keywords);

/** Anything a request can point at. */
const REFERENCE = [
    ...new Set<string>([...LINK_NOUNS, ...SECTION_WORDS, ...ANIMEX_NAMES]),
].join("|");

const REQUEST_VERBS = "send|share|drop|give|gimme|paste|dm|post|link|pass|hand|show|tell";

const POLITE = "pls|plz|please";

const MEDIA_WORDS = ["watch", "watching", "stream", "streaming"] as const;

const NAME = ANIMEX_NAMES.join("|");
const SITE_NOUN = "url|link|website|site|homepage|page";
const SECTION_WORD = SECTION_WORDS.join("|");

const DESTINATION = String.raw`(?:(?:${NAME})(?:\s+(?:${SITE_NOUN}|one|${SECTION_WORD})(?:\s+(?:page|link|url))?)?|(?:${SITE_NOUN})|(?:${SECTION_WORD})(?:\s+(?:page|link|url))?)\b`;

const OBJECT_PRONOUN = "me|us|it|them";
const DETERMINER = "the|a|an|that|this|those|these|your|ur|its|dat";
const ADJECTIVE =
    "official|new|real|actual|latest|current|working|proper|correct|right|direct|updated|main|original";

/** The only words allowed between an ask and its destination. */
const FILLER = `(?:${OBJECT_PRONOUN}|${DETERMINER}|${ADJECTIVE}|${NAME}|${SITE_NOUN})`;
const FILL = String.raw`(?:${FILLER}\s+){0,5}`;

const LEAD_WORDS = [
    "hey|hi|hello|yo|ok|okay|um|uh|hmm|well|just|quick|sorry|lol|bro|bruh|dude|man|mate",
    "guys|everyone|everybody|folks|people|chat|fam|gang|team|mod|mods|admin",
    "new|here|excuse|me|question|q",
    "pls|plz|please|kindly|thanks|thx|ty",
    "anyone|anybody|someone|somebody|can|could|would|will|you|u|ya|yall|y all",
].join("|");

const LEAD = String.raw`(?:(?:${LEAD_WORDS})\s+){0,6}`;

const TRAIL = String.raw`(?:\s+(?:pls|plz|please|thanks|thx|ty|again|here|rn|now|asap))*$`;

/** The other words the frames spell out; the typo repair leaves them alone. */
const FRAME_WORDS =
    "is|are|was|were|s|can|could|should|do|does|did|would|will|may|might|to|else|tf|i|im|we|you|u|one|someone|anyone|anybody|somebody|ppl|people|yall|ya|find|get|go|access|open|reach|visit|see|watch|stream|browse|download|need|want|looking|look|searching|trying|for|have|got|know|guys|how|what|whats|where|wheres|which|again|here|rn|now|asap|with|of|from|in|on|into|page|link|url|anime|episode|show";

const SITE = "website|site";

/** Things that turn a site mention into hosting, design or outage talk. */
const SITE_TROUBLE =
    "builder|template|host|hosted|hosting|design|development|domain|registrar|down|broken|error|not working|work|blocked|blocker";

/** Asking for a good/best site is a recommendation request, not our link. */
const RECOMMENDATION =
    "best|better|worse|good|great|legit|safe|safer|safest|reliable|fastest|recommend|recommendation|suggest|suggestion|alternative";

/** Their own project: "a link to my portfolio" is not an AnimeX request. */
const PERSONAL_PROJECTS =
    "portfolio|project|business|company|repo|repository|blog|store|shop|startup";

/** A link to one of these is not a link to AnimeX. */
const OTHER_SERVICES =
    "youtube|netflix|hulu|disney|prime video|crunchyroll|spotify|soundcloud|twitch|twitter|instagram|tiktok|facebook|reddit|github|steam|discord|myanimelist|anilist|imdb|wikipedia|google";

/** Questions may contain "I have"; statements may not. */
const QUESTION_START =
    "what|whats|where|wheres|which|how|can|could|may|would|do|does|did|is|are|anyone|anybody";

const STATEMENT_VERBS = "have|had|got|made|found|like|love|sent|saw|use";

/** Includes the contractions apostrophe stripping creates ("i'd" is "id"). */
const FIRST_PERSON = "i|im|id|ive|ill|we|weve";

const NOT_QUESTION = String.raw`(?:(?!(?:${QUESTION_START})\b)[a-z0-9]+\s+)*`;

/** Generated, not hand-edited: `bun scripts/typo-guard.ts <word list>`. */
const TYPO_GUARD = words(`
    amy aws crop dose drip droop ese five form fro gibe giver gives gte hare
    hats hive juts kink lease lino mani noe odes oink pink pleas pleased pleases
    pots rae sends sens shade shard shared sharer shares sire sited sits snare
    steam streak suite swatch thees weer wend whee whereas
`);

